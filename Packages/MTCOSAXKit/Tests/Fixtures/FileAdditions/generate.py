# Generates cases.json for Satimage File Additions (everything but the dialogs), recorded from SatimageOSAX.
# Every case works in its own folder, $TMP/<case>, and builds what it needs with recorded commands (mkdir,
# writetext, create symlink), so replays rebuild the same setup. Run: python3 generate.py
import json, os

cases, names = [], set()
def case(name, *lines):
    assert name.lower() not in names, name
    names.add(name.lower())
    # "@" stands for the case's folder where it starts a path ("@/…", "@"), not in URLs like "user@host".
    body = "\n".join(line.replace("@/", f"$TMP/{name}/").replace('"@"', f'"$TMP/{name}"') for line in lines)
    cases.append({"name": name, "script": f'mkdir (POSIX file "$TMP/{name}")\n' + body})

F = lambda path: f'(POSIX file "@/{path}")'           # a file reference
A = lambda path: f'(POSIX file "@/{path}" as alias)'  # an alias
S = lambda path: f'"@/{path}"'                         # a POSIX path string
make = lambda path, text="x": f'writetext "{text}" to {F(path)}'
OLD = 'date "Saturday, January 1, 2000 at 12:00:00 AM"'
FUTURE = 'date "Friday, January 1, 2100 at 12:00:00 AM"'

# A folder with files of different kinds and cases, a hidden file, a subfolder tree, a package and an empty folder.
